// Fluxo site → página do Lab → Lab em outra aba → login obrigatório → cadastro (credenciais de teste geradas aqui).
import { chromium } from "@playwright/test";
import { randomBytes } from "node:crypto";
const site = process.argv[2] ?? "http://localhost:8080";
const out = "test-results/inspecao";
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
const errors = [];
ctx.on("page", (p) => p.on("pageerror", (e) => errors.push(e.message)));
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(site + "/", { waitUntil: "networkidle" });
await page.screenshot({ path: `${out}/site-1-inicio.png` });
await page.locator(".lab-link").click();
await page.waitForURL(/\/lab\/$/);
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/site-2-pagina-lab.png` });
const href = await page.locator("#abrirLab").getAttribute("href");
const target = await page.locator("#abrirLab").getAttribute("target");
console.log("botão:", href, target);
const [lab] = await Promise.all([ctx.waitForEvent("page"), page.locator("#abrirLab").click()]);
await lab.waitForLoadState("networkidle");
console.log("nova aba:", lab.url());
await lab.screenshot({ path: `${out}/lab-1-entrar.png` });
await lab.getByRole("link", { name: "Criar conta" }).first().click();
await lab.waitForURL(/cadastro/);
const email = `teste+${randomBytes(4).toString("hex")}@exemplo.test`;
const senha = randomBytes(12).toString("base64url");
await lab.getByLabel("Nome completo").fill("Pesquisadora Teste");
await lab.getByLabel("E-mail").fill(email);
await lab.getByLabel("Senha", { exact: true }).fill(senha);
await lab.getByLabel("Confirmar senha").fill(senha);
await lab.getByRole("checkbox").check();
await lab.screenshot({ path: `${out}/lab-2-cadastro.png` });
await lab.getByRole("button", { name: "Criar conta e entrar" }).click();
await lab.waitForURL(/laboratorio|projetos/, { timeout: 30000 });
await lab.waitForTimeout(3000);
await lab.screenshot({ path: `${out}/lab-3-apos-cadastro.png` });
console.log("após cadastro:", lab.url());
console.log(errors.length ? `erros: ${errors.join(" | ")}` : "sem erros de página");
await browser.close();
